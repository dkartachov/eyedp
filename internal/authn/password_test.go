package authn

import (
	"errors"
	"regexp"
	"testing"
)

var phcRegex = regexp.MustCompile(`^\$argon2id\$v=19\$m=65536,t=3,p=4\$[A-Za-z0-9+/]{22}\$[A-Za-z0-9+/]{43}$`)

func TestHashPassword(t *testing.T) {
	password := "Password123!"

	t.Run("ValidPHCFormat", func(t *testing.T) {
		hash := HashPassword(password)

		if !phcRegex.MatchString(hash) {
			t.Errorf("expected hash to match PHC format, got: %s", hash)
		}
	})

	t.Run("UniqueHashesForSamePassword", func(t *testing.T) {
		hash1 := HashPassword(password)
		hash2 := HashPassword(password)

		if hash1 == hash2 {
			t.Errorf("expected different hashes for the same password, got: %s and %s", hash1, hash2)
		}
	})

}

// TODO(review): improvements for TestVerifyPassword
//   - Add a known-answer test: a PHC string generated by an independent
//     implementation (e.g. the argon2 CLI), so a bug shared by HashPassword
//     and VerifyPassword (like swapped time/memory) is caught.
//   - Add cases for pathological parameters once VerifyPassword bounds them:
//     t=0, p=0, empty key section, huge m. They panic today.
//   - The "invalid key encoding" case uses a short salt ("salt123"); once salt
//     length is validated it will fail at the salt step instead. Use a valid
//     22-char salt there.

func TestVerifyPassword(t *testing.T) {
	storedHash := HashPassword("Password123!")

	tests := []struct {
		name       string
		password   string
		storedHash string
		wantErr    error
	}{
		{
			name:       "valid password",
			password:   "Password123!",
			storedHash: storedHash,
			wantErr:    nil,
		},
		{
			name:       "invalid password",
			password:   "Password321?",
			storedHash: storedHash,
			wantErr:    ErrInvalidPassword,
		},
		{
			name:       "invalid identifier",
			password:   "Password123!",
			storedHash: "$argon2$v=19$m=65536,t=3,p=4$invalidsalt$invalidhash",
			wantErr:    ErrMalformedHash,
		},
		{
			name:       "invalid hash format",
			password:   "Password123!",
			storedHash: "$argon2id$v=19$m=65536,t=3,p=4$hash123",
			wantErr:    ErrMalformedHash,
		},
		{
			name:       "invalid argon2 version",
			password:   "Password123!",
			storedHash: "$argon2id$v=nineteen$m=65536,t=3,p=4$salt123$hash123",
			wantErr:    ErrMalformedHash,
		},
		{
			name:       "unsupported argon2 version",
			password:   "Password123!",
			storedHash: "$argon2id$v=18$m=65536,t=3,p=4$salt123$hash123",
			wantErr:    ErrMalformedHash,
		},
		{
			name:       "invalid parameters",
			password:   "Password123!",
			storedHash: "$argon2id$v=19$m=65536,t=3$salt123$hash123",
			wantErr:    ErrMalformedHash,
		},
		{
			name:       "invalid salt encoding",
			password:   "Password123!",
			storedHash: "$argon2id$v=19$m=65536,t=3,p=4$invalid???salt$hash123",
			wantErr:    ErrMalformedHash,
		},
		{
			name:       "invalid key encoding",
			password:   "Password123!",
			storedHash: "$argon2id$v=19$m=65536,t=3,p=4$salt123$invalid???hash",
			wantErr:    ErrMalformedHash,
		},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			err := VerifyPassword(tc.password, tc.storedHash)

			if tc.wantErr == nil {
				if err != nil {
					t.Errorf("expected no error, got %v", err)
				}
				return
			}

			if !errors.Is(err, tc.wantErr) {
				t.Errorf("expected error %v, got %v", tc.wantErr, err)
			}
		})
	}
}
